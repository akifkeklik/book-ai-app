/**
 * Every supported language. The type forces each dictionary to define every key,
 * so a missing translation fails the TypeScript build instead of reaching users.
 */
export const LOCALES: Record<Language, Record<TranslationKey, string>> = { ...DICTIONARIES, es, fr, it };

/** Slug used for genre keys: "Biography & Memoir" -> "genre_biography_memoir". */
export function genreKey(name: string): string {
  return 'genre_' + name.toLowerCase().replace(/[^a-z0-9]/g, '_').replace(/_+/g, '_').replace(/^_|_$/g, '');
}

/** Localized genre/category name; unknown (raw catalog) categories are shown as-is. */
export function translateGenre(lang: Language, name: string): string {
  const key = genreKey(name) as TranslationKey;
  const dict = LOCALES[lang] || LOCALES.en;
  return dict[key] || LOCALES.en[key] || name;
}

export function translate(lang: Language, key: TranslationKey, args?: Record<string, string | number>): string {
  const dict = LOCALES[lang] || LOCALES.en;
  let text: string = dict[key] || LOCALES.en[key] || key;

  if (args) {
    for (const [k, v] of Object.entries(args)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }

  return text;
}

export function localizeRecommendationReason(
  reason: string,
  t: (key: TranslationKey, args?: Record<string, string | number>) => string
): string {
  if (!reason) return '';
  const lower = reason.toLowerCase().trim();
  if (lower.includes('trending on libris')) {
    return t('trending_on_libris');
  }
  if (
    lower.includes('personalized taste') ||
    lower.includes('based on your taste') ||
    lower.includes('curated based on your taste profile')
  ) {
    return t('based_on_your_taste');
  }
  const pathMatch = /(?:for learning path|for your learning path) '([^']+)'/i.exec(reason);
  if (pathMatch) return t('reason_learning_path', { title: pathMatch[1] });

  const takeawayMatch = /deepens (?:takeaways|topics) from (?:your key takeaways on )?'([^']+)'/i.exec(reason);
  if (takeawayMatch) return t('reason_takeaway', { title: takeawayMatch[1] });

  const likeMatch = /because you liked '([^']+)'/i.exec(reason);
  if (likeMatch) return t('reason_because_you_liked', { title: likeMatch[1] });

  const readMatch = /because you read '([^']+)'/i.exec(reason);
  if (readMatch) return t('reason_because_you_read', { title: readMatch[1] });

  const readingMatch = /because you're reading '([^']+)'/i.exec(reason);
  if (readingMatch) return t('reason_currently_reading', { title: readingMatch[1] });

  const notesMatch = /based on your notes for '([^']+)'/i.exec(reason);
  if (notesMatch) return t('reason_based_on_notes', { title: notesMatch[1] });

  const favMatch = /because you favorited '([^']+)'/i.exec(reason);
  if (favMatch) return t('reason_favorited', { title: favMatch[1] });

  const listMatch = /from your reading list:\s*'([^']+)'/i.exec(reason);
  if (listMatch) return t('reason_from_reading_list', { title: listMatch[1] });

  const simMatch = /similar to '([^']+)'/i.exec(reason);
  if (simMatch) return t('reason_similar_to', { title: simMatch[1] });

  const enjoyMatch = /because you enjoy (.+)/i.exec(reason);
  if (enjoyMatch) return t('reason_enjoy_genre', { genre: enjoyMatch[1] });

  const authorMatch = /by your preferred author (.+)/i.exec(reason);
  if (authorMatch) return t('reason_author', { author: authorMatch[1] });

  return reason;
}

